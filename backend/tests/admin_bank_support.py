async def build_db():
    engine = create_async_engine("sqlite+aiosqlite://", poolclass=StaticPool)
    ddl = run_path(str(VERSIONS / "0002_base_content.py"))["STATEMENTS"]
    async with engine.begin() as conn:
        await conn.run_sync(Base.metadata.create_all)
        for statement in ddl:
            await conn.exec_driver_sql(statement.replace("integer GENERATED BY DEFAULT AS IDENTITY", "integer")
                                       .replace("DEFAULT now()", "DEFAULT CURRENT_TIMESTAMP"))
        await conn.exec_driver_sql("ALTER TABLE questions ADD COLUMN archived_at timestamp NULL")  # 0021
        for statement in SEED:
            await conn.exec_driver_sql(statement)
    return engine, async_sessionmaker(engine, expire_on_commit=False)


async def bearer(client, email: str, password: str) -> dict:
    r = await client.post(f"{API}/auth/login", json={"email": email, "password": password})
    assert r.status_code == 200, r.text
    token = client.cookies[COOKIE]
    client.cookies.clear()
    return {"Authorization": f"Bearer {token}"}


async def admin_headers(client, db) -> dict:
    pw = new_password()
    await make_admin(db, "admin11@example.com", pw)
    return await bearer(client, "admin11@example.com", pw)


async def student_headers(client) -> dict:
    pw = new_password()
    r = await register(client, email="hs11@example.com", password=pw)
    assert r.status_code in (200, 201), r.text
    client.cookies.clear()
    return await bearer(client, "hs11@example.com", pw)
